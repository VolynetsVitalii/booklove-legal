/* landing.js — единственный скрипт сайта BooksLove.
   T-230 (Блок 1A v1.1 — лендинг-сайт и веб-присутствие).

   ─────────────────────────────────────────────────────────────────────────
   ЧТО ЭТОТ ФАЙЛ ДЕЛАЕТ (и, что важнее, чего НЕ делает)
   ─────────────────────────────────────────────────────────────────────────
   Делает пять вещей:
     1. Помечает <html> классом «js», чтобы CSS понял, что скрипт живой.
     2. Показывает секции по мере прокрутки (IntersectionObserver).
     3. Сворачивает соседние ответы FAQ, когда раскрывают новый.
     4. Ведёт липкую сцену: меняет кадр на телефоне по мере прокрутки.
     5. Рисует индикатор прокрутки и подставляет год в подвал.

   НЕ делает: не собирает статистику, не ставит cookie, не обращается ни к
   одному внешнему адресу, не читает и не пишет localStorage. Сайт
   приложения, которое обещает «no cross-app tracking» (T-394), не может
   позволить себе ни одну из этих строк — и сторож Scripts/landing-audit.sh
   проверяет, что внешних запросов на страницах нет вовсе.

   ─────────────────────────────────────────────────────────────────────────
   ПОЧЕМУ СКРИПТ ПОДКЛЮЧАЕТСЯ С АТРИБУТОМ defer
   ─────────────────────────────────────────────────────────────────────────
   <script defer src="assets/landing.js"> загружается ПАРАЛЛЕЛЬНО разбору
   HTML и выполняется, когда документ уже построен. Без defer браузер
   останавливает разбор страницы, и первый экран рисуется позже. При этом
   defer гарантирует, что document.querySelectorAll найдёт все элементы —
   отдельная подписка на DOMContentLoaded не нужна.

   ─────────────────────────────────────────────────────────────────────────
   ПОЧЕМУ ВСЁ ОБЁРНУТО В ФУНКЦИЮ
   ─────────────────────────────────────────────────────────────────────────
   Немедленно вызываемая функция (IIFE) держит переменные при себе. Без
   обёртки `var observer` стал бы свойством window и мог бы столкнуться с
   чем угодно — например, со встроенным скриптом на 404.html.

   'use strict' включает строгий режим: опечатка в имени переменной станет
   ошибкой в консоли, а не молча создаст новую глобальную переменную.       */

(function () {
  'use strict';

  // ═══════════════════════════════════════════════════════════════════════
  // 1. Отметка «JavaScript работает»
  // ═══════════════════════════════════════════════════════════════════════
  // CSS прячет .reveal только внутри правила `.js .reveal`. Пока этого
  // класса нет — содержимое видно. Так страница остаётся полностью
  // читаемой при отключённом или упавшем JavaScript, в режиме чтения Safari
  // и для поискового робота, который не выполнил скрипт.
  //
  // Класс ставится ПЕРВОЙ строкой, до всего остального: если бы он стоял
  // после наблюдателя, между показом страницы и появлением класса
  // содержимое успело бы моргнуть.
  document.documentElement.classList.add('js');

  // ═══════════════════════════════════════════════════════════════════════
  // 2. Уважение к настройке «уменьшить движение»
  // ═══════════════════════════════════════════════════════════════════════
  // matchMedia спрашивает у системы то же, что @media (prefers-reduced-motion)
  // спрашивает в CSS. Если человек попросил меньше движения, наблюдатель
  // вообще не создаётся: незачем тратить работу на анимацию, которую CSS
  // всё равно погасит.
  var reduceMotion = window.matchMedia &&
                     window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  // Все элементы, помеченные в разметке классом «reveal».
  // querySelectorAll возвращает статический список — он не меняется, даже
  // если позже в документ что-то добавят. Нам этого достаточно: содержимое
  // страницы статично.
  var revealables = document.querySelectorAll('.reveal');

  // ═══════════════════════════════════════════════════════════════════════
  // 3. Появление при прокрутке
  // ═══════════════════════════════════════════════════════════════════════
  // IntersectionObserver — механизм самого браузера: он сам следит за тем,
  // попал ли элемент в поле зрения, и зовёт нас только при изменении.
  //
  // Альтернатива — обработчик события scroll с вызовом getBoundingClientRect
  // на каждом элементе. Она стоит несравнимо дороже: scroll срабатывает
  // десятки раз в секунду, а getBoundingClientRect заставляет браузер
  // пересчитать раскладку СИНХРОННО (layout thrashing). На слабом телефоне
  // это прямая потеря кадров при прокрутке — ровно там, где плавность
  // заметнее всего.
  //
  // Проверка `'IntersectionObserver' in window` — не суеверие: если
  // механизма нет (очень старый браузер), мы просто показываем всё сразу.
  if (reduceMotion || !('IntersectionObserver' in window)) {
    // Показать всё немедленно и выйти из этой части.
    for (var i = 0; i < revealables.length; i++) {
      revealables[i].classList.add('is-in');
    }
  } else {
    var observer = new IntersectionObserver(function (entries) {
      // entries — только те элементы, чья видимость ИЗМЕНИЛАСЬ с прошлого
      // вызова, а не весь список. Поэтому цикл всегда короткий.
      for (var j = 0; j < entries.length; j++) {
        var entry = entries[j];

        // isIntersecting === true означает «пересёк заданный порог».
        if (!entry.isIntersecting) { continue; }

        entry.target.classList.add('is-in');

        // Отписываемся сразу: анимация появления одноразовая. Без unobserve
        // наблюдатель продолжал бы дёргать нас на каждом проходе элемента
        // через край экрана — работа впустую до конца сессии.
        observer.unobserve(entry.target);
      }
    }, {
      // Порог 0.12 = «видно хотя бы 12 % элемента». Ноль запускал бы
      // анимацию, когда виден один пиксель — движение начиналось бы за
      // краем экрана и человек его не видел. Единица (100 %) для высокой
      // секции не наступила бы никогда.
      threshold: 0.12,

      // Отрицательный нижний отступ поднимает «линию срабатывания» на 40 px
      // выше нижнего края окна. Элемент успевает проявиться до того, как
      // человек на него посмотрит, и появление не выглядит запоздалым.
      rootMargin: '0px 0px -40px 0px'
    });

    for (var k = 0; k < revealables.length; k++) {
      observer.observe(revealables[k]);
    }
  }

  // ═══════════════════════════════════════════════════════════════════════
  // 4. FAQ: раскрыт всегда один ответ
  // ═══════════════════════════════════════════════════════════════════════
  // Аккордеон СОБРАН НА <details>/<summary> и работает без этого кода:
  // браузер сам раскрывает и сворачивает, клавиатура сама им управляет,
  // VoiceOver сам объявляет состояние. Скрипт добавляет единственную вещь —
  // сворачивает соседей, чтобы список вопросов не превращался в простыню.
  //
  // Событие 'toggle' срабатывает и на раскрытие, и на сворачивание, поэтому
  // проверяем `open` явно: без проверки закрытие одного ответа запускало бы
  // холостой проход по всем остальным.
  var faqItems = document.querySelectorAll('.faq details');

  for (var m = 0; m < faqItems.length; m++) {
    faqItems[m].addEventListener('toggle', function (event) {
      if (!event.target.open) { return; }

      for (var n = 0; n < faqItems.length; n++) {
        if (faqItems[n] !== event.target) {
          faqItems[n].open = false;
        }
      }
    });
  }

  // ═══════════════════════════════════════════════════════════════════════
  // 5. Липкая сцена: смена кадра на телефоне по мере прокрутки
  // ═══════════════════════════════════════════════════════════════════════
  // Разметка: у каждой текстовой главы есть атрибут data-shot="library", и у
  // каждого кадра в телефоне — такой же. Задача — держать активным ровно один.
  //
  // ПОЧЕМУ СВЯЗЬ ЧЕРЕЗ АТРИБУТ, А НЕ ЧЕРЕЗ ПОРЯДКОВЫЙ НОМЕР
  //   С номерами перестановка двух глав в разметке молча показывала бы чужой
  //   экран, и заметить это можно только глазами. Имя кадра ломается громко:
  //   картинка просто не найдётся.
  //
  // ПОЧЕМУ ЗДЕСЬ НЕ IntersectionObserver
  //   Первая версия использовала его — и кадр застревал. Наблюдатель зовёт нас
  //   только в МОМЕНТ пересечения порога. Между двумя порогами он молчит,
  //   поэтому на длинной главе состояние оставалось от предыдущей: текст главы
  //   два уже занимал экран, а телефон всё ещё показывал экран главы один.
  //   Повышать число порогов — лечить симптом: между любыми двумя порогами
  //   остаётся промежуток.
  //
  //   Здесь нужен не «кто вошёл», а «кто СЕЙЧАС ближе к цели» — величина,
  //   которую надо пересчитывать непрерывно. Это делает общий цикл прокрутки
  //   ниже: пять вызовов getBoundingClientRect на кадр стоят микросекунды и,
  //   в отличие от разобранного выше случая, не чередуются с записью в
  //   раскладку — то есть браузеру нечего пересчитывать заново.
  var sceneSteps = [];
  var sceneShots = {};
  var currentShot = '';

  (function collectScene() {
    var all = document.querySelectorAll('[data-shot]');
    for (var s = 0; s < all.length; s++) {
      if (all[s].classList.contains('scene__shot')) {
        sceneShots[all[s].getAttribute('data-shot')] = all[s];
      } else {
        sceneSteps.push(all[s]);
      }
    }
  })();

  function updateScene() {
    if (!sceneSteps.length) { return; }

    var viewport = window.innerHeight || document.documentElement.clientHeight;
    // Целимся не в центр окна, а немного выше: глаз читает верхнюю треть
    // экрана, и переключать кадр по ней естественнее.
    var aim = viewport * 0.42;

    var winner = null;
    var bestDistance = Infinity;

    for (var i = 0; i < sceneSteps.length; i++) {
      var box = sceneSteps[i].getBoundingClientRect();
      var centre = box.top + box.height / 2;
      var distance = Math.abs(centre - aim);

      if (distance < bestDistance) {
        bestDistance = distance;
        winner = sceneSteps[i];
      }
    }

    if (!winner) { return; }

    var name = winner.getAttribute('data-shot');
    // Ничего не трогаем, если победитель тот же: лишние записи в classList
    // заставляют браузер пересчитывать стили без причины.
    if (name === currentShot) { return; }
    currentShot = name;

    for (var key in sceneShots) {
      if (Object.prototype.hasOwnProperty.call(sceneShots, key)) {
        sceneShots[key].classList.toggle('is-active', key === name);
      }
    }
    for (var j = 0; j < sceneSteps.length; j++) {
      sceneSteps[j].classList.toggle('is-active', sceneSteps[j] === winner);
    }
  }

  // ═══════════════════════════════════════════════════════════════════════
  // 6. Индикатор прокрутки
  // ═══════════════════════════════════════════════════════════════════════
  // Полоска вверху окна показывает, какая доля страницы пройдена.
  //
  // ПОЧЕМУ ЗДЕСЬ ОБРАБОТЧИК scroll, ХОТЯ ВЫШЕ ОТ НЕГО ОТКАЗАЛИСЬ
  //   Выше речь шла о чтении раскладки на каждом кадре — вот это дорого.
  //   Здесь мы только ПИШЕМ ширину, а единственную дорогую величину
  //   (полную высоту документа) считаем один раз и пересчитываем лишь при
  //   изменении размера окна. Плюс `{ passive: true }` — обещание браузеру,
  //   что обработчик не отменит прокрутку, и тот не ждёт его завершения.
  var bar = document.querySelector('.progress');

  if (bar) {
    var limit = 0;

    var measure = function () {
      limit = Math.max(
        document.documentElement.scrollHeight - window.innerHeight, 1
      );
    };

    var paint = function () {
      var done = Math.min(window.scrollY / limit, 1);
      bar.style.width = (done * 100).toFixed(2) + '%';
      // Сцена живёт в том же цикле: один обработчик прокрутки на страницу,
      // а не два независимых.
      updateScene();
    };

    // rAF-заслонка: браузер зовёт нас не чаще одного раза на кадр, сколько
    // бы событий прокрутки ни пришло между кадрами.
    var ticking = false;
    var onScroll = function () {
      if (ticking) { return; }
      ticking = true;
      window.requestAnimationFrame(function () {
        paint();
        ticking = false;
      });
    };

    measure();
    paint();
    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', function () { measure(); paint(); });
  }

  // Страховка: если индикатора прокрутки на странице нет (а сцена есть),
  // цикл выше не создастся — тогда ведём сцену собственным обработчиком.
  if (!bar && sceneSteps.length) {
    var sceneTicking = false;
    updateScene();
    window.addEventListener('scroll', function () {
      if (sceneTicking) { return; }
      sceneTicking = true;
      window.requestAnimationFrame(function () {
        updateScene();
        sceneTicking = false;
      });
    }, { passive: true });
  }

  // ═══════════════════════════════════════════════════════════════════════
  // 7. Год в подвале
  // ═══════════════════════════════════════════════════════════════════════
  // Год, вписанный в HTML руками, устаревает 1 января и выглядит как
  // заброшенный сайт. Один элемент с data-year решает это навсегда.
  // Если JavaScript не выполнится, в разметке остаётся год выпуска —
  // не пусто, просто не обновлено.
  var yearSlots = document.querySelectorAll('[data-year]');
  var currentYear = String(new Date().getFullYear());

  for (var p = 0; p < yearSlots.length; p++) {
    yearSlots[p].textContent = currentYear;
  }
})();
